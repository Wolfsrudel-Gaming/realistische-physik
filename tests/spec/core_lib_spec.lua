local wmath, Units, Curve, Vec, Table = WRP.Math, WRP.Units, WRP.Curve, WRP.Vec, WRP.Table

describe("wmath", function()
    it("clamps", function()
        expect.eq(wmath.clamp(5, 0, 1), 1)
        expect.eq(wmath.clamp(-5, 0, 1), 0)
        expect.eq(wmath.clamp(0.5, 0, 1), 0.5)
    end)
    it("remaps with clamping", function()
        expect.near(wmath.remap(5, 0, 10, 0, 100), 50)
        expect.near(wmath.remap(20, 0, 10, 0, 100), 100)
    end)
    it("applies deadzone and rescales", function()
        expect.eq(wmath.deadzone(0.05, 0.1), 0.0)
        expect.near(wmath.deadzone(1.0, 0.1), 1.0)
        expect.near(wmath.deadzone(-0.55, 0.1), -0.5)
    end)
    it("lowpass converges", function()
        local v = 0.0
        for _ = 1, 1000 do v = wmath.lowpass(v, 10.0, 0.01, 0.5) end
        expect.near(v, 10.0, 1e-3)
    end)
    it("PI controller drives error to zero", function()
        local pi = wmath.newPI(0.5, 2.0, -10, 10)
        local x, target = 0.0, 1.0
        for _ = 1, 2000 do
            local u = pi:step(target - x, 0.01)
            x = x + (u - x) * 0.01 * 5
        end
        expect.near(x, 1.0, 0.02)
    end)
end)

describe("units", function()
    it("converts speed", function()
        expect.near(Units.msToKmh(10), 36)
        expect.near(Units.kmhToMs(100), 27.7778, 1e-3)
        expect.near(Units.msToMph(Units.kmhToMs(100)), 62.137, 1e-2)
    end)
    it("converts power and torque", function()
        expect.near(Units.psToW(100), 73549.875, 1e-2)
        expect.near(Units.wToHp(Units.psToW(100)), 98.632, 1e-2)
        expect.near(Units.lbftToNm(100), 135.58, 1e-2)
    end)
    it("converts rpm to rad/s and back", function()
        expect.near(Units.rpmToRads(60), 2 * math.pi)
        expect.near(Units.radsToRpm(Units.rpmToRads(3000)), 3000)
    end)
    it("converts temperature", function()
        expect.near(Units.kToC(Units.cToK(90)), 90)
        expect.near(Units.cToF(100), 212)
    end)
end)

describe("curve", function()
    it("interpolates and clamps", function()
        local c = Curve.new { { 1000, 100 }, { 3000, 200 }, { 2000, 150 } }
        expect.near(c:at(1500), 125)
        expect.near(c:at(500), 100)
        expect.near(c:at(5000), 200)
        local m, mx = c:max()
        expect.eq(m, 200); expect.eq(mx, 3000)
    end)
    it("2D map bilinear", function()
        local m = Curve.Map2.new({ 0, 10 }, { 0, 10 }, { { 0, 10 }, { 10, 20 } })
        expect.near(m:at(5, 5), 10)
        expect.near(m:at(10, 10), 20)
        expect.near(m:at(-1, -1), 0)
    end)
end)

describe("vec", function()
    it("does arithmetic", function()
        local a, b = Vec.new(1, 2, 3), Vec.new(4, 5, 6)
        expect.eq(a + b, Vec.new(5, 7, 9))
        expect.near(Vec.dot(a, b), 32)
        expect.eq(Vec.cross(Vec.new(1, 0, 0), Vec.new(0, 1, 0)), Vec.new(0, 0, 1))
        expect.near(Vec.len(Vec.new(3, 4, 0)), 5)
    end)
end)

describe("deepmerge", function()
    it("merges maps and replaces arrays", function()
        local base = { a = 1, b = { c = 2, d = 3 }, arr = { 1, 2, 3 } }
        local out = Table.deepmerge(base, { b = { d = 4 }, arr = { 9 } })
        expect.eq(out.a, 1); expect.eq(out.b.c, 2); expect.eq(out.b.d, 4)
        expect.eq(#out.arr, 1); expect.eq(out.arr[1], 9)
        expect.eq(base.b.d, 3, "base untouched")
    end)
end)
